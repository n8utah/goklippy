package main

import (
	"goklippy/backend/config"
	"goklippy/backend/routes"

	"github.com/gin-gonic/gin"
)

func registerRoutes(r *gin.Engine, cfg config.Config) {
	api := r.Group("/api/v1")

	api.GET("/health", routes.Health)
	api.POST("/auth/login", routes.LoginHandler())
	api.POST("/auth/refresh", routes.RefreshHandler())
	api.POST("/auth/logout", routes.LogoutHandler())
	api.GET("/auth/me", routes.RequireJWT(), routes.Me)

	klipper := api.Group("/klipper-config")
	klipper.GET("/files", routes.ListKlipperConfigFiles)
	klipper.POST("/load", routes.LoadKlipperConfig)
	klipper.GET("/workspace", routes.GetKlipperConfigWorkspace)
	klipper.PUT("/sections/*name", routes.UpdateKlipperConfigSection)
	klipper.DELETE("/sections/*name", routes.DeleteKlipperConfigSection)
	klipper.PUT("/raw", routes.UpdateKlipperConfigRaw)
	klipper.POST("/save", routes.SaveKlipperConfig)

	boards := api.Group("/board-profiles")
	boards.GET("", routes.ListBoardProfiles)
	boards.GET("/:id", routes.GetBoardProfile)
	boards.GET("/:id/diagram", routes.GetBoardProfileDiagram)
	boards.GET("/:id/image", routes.ServeBoardProfileImage)
	boards.GET("/:id/editor", routes.GetBoardProfileEditor)
	boards.PUT("/:id/hotspots", routes.UpdateBoardProfileHotspots)

	mcuGroup := api.Group("/mcu")
	mcuGroup.GET("/ports", routes.GetMCUPorts)
	mcuGroup.POST("/scan", routes.ScanMCUPorts)
	mcuGroup.POST("/connect", routes.ConnectMCU)
	mcuGroup.POST("/disconnect", routes.DisconnectMCU)
	mcuGroup.GET("/sessions", routes.ListMCUSessions)
	mcuGroup.GET("/sessions/:id", routes.GetMCUSession)
	mcuGroup.GET("/sessions/:id/ws", routes.MCUSessionWebSocket)
	mcuGroup.GET("/sessions/:id/readings", routes.GetMCUReadings)
	mcuGroup.POST("/sessions/:id/digital-out", routes.SetMCUDigitalOut)
	mcuGroup.POST("/sessions/:id/servo", routes.SetMCUServo)
	mcuGroup.POST("/sessions/:id/pca9685/check", routes.CheckMCUPCA9685)
	mcuGroup.POST("/sessions/:id/reset", routes.ResetMCU)
	mcuGroup.POST("/sessions/:id/stepper/jog", routes.JogMCUStepper)
	mcuGroup.POST("/sessions/:id/stepper/routine", routes.StartMCUStepperRoutine)
	mcuGroup.POST("/sessions/:id/stepper/index", routes.IndexMCUStepper)
	mcuGroup.POST("/sessions/:id/stepper/stop", routes.StopMCUStepper)

	sorterGroup := api.Group("/sorter")
	sorterGroup.GET("/settings/:name", routes.GetSorterSettings)
	sorterGroup.PUT("/settings/:name", routes.PutSorterSettings)
	sorterGroup.GET("/state", routes.GetSorterState)
	sorterGroup.POST("/commands", routes.SorterCommand)
	sorterGroup.POST("/channels/clear", routes.ClearSorterChannels)
	sorterGroup.POST("/channels/:channel/move", routes.MoveSorterChannel)
	sorterGroup.POST("/channels/:channel/shake", routes.ShakeSorterChannel)
	sorterGroup.POST("/channels/:channel/forget-ignored", routes.ForgetSorterIgnored)
	sorterGroup.GET("/shakes", routes.ListSorterShakes)
	sorterGroup.GET("/ws", routes.SorterWebSocket)
	sorterGroup.GET("/chute", routes.GetSorterChute)
	sorterGroup.POST("/chute/aim", routes.AimSorterChute)
	sorterGroup.POST("/chute/zero", routes.ZeroSorterChute)
	sorterGroup.POST("/lights", routes.SetSorterLights)
	sorterGroup.POST("/lights/blink", routes.BlinkSorterLights)
	sorterGroup.POST("/chute/calibrate", routes.CalibrateSorterChute)
	sorterGroup.POST("/distribution/send", routes.SendToSorterBin)
	sorterGroup.POST("/distribution/test", routes.TestSorterLayer)
	sorterGroup.POST("/jobs/cancel", routes.CancelSorterJob)
	sorterGroup.GET("/profiles", routes.ListSortingProfiles)
	sorterGroup.POST("/profiles", routes.ImportSortingProfile)
	sorterGroup.POST("/profiles/:id/activate", routes.ActivateSortingProfile)
	sorterGroup.DELETE("/profiles/:id", routes.DeleteSortingProfile)
	sorterGroup.GET("/bins", routes.GetSorterBins)
	sorterGroup.PUT("/bins/:layer/:bin", routes.SetSorterBin)
	sorterGroup.POST("/bins/reset", routes.ResetSorterBins)
	sorterGroup.POST("/bins/:layer/:bin/empty", routes.EmptySorterBin)
	sorterGroup.GET("/kits", routes.GetSorterKits)
	sorterGroup.POST("/route", routes.RouteSorterPiece)
	sorterGroup.POST("/identify", routes.IdentifySorterPiece)
	sorterGroup.GET("/pieces", routes.ListSorterPieces)
	sorterGroup.GET("/pieces/:id", routes.GetSorterPiece)
	sorterGroup.GET("/pieces/:id/images/:idx", routes.GetSorterPieceImage)
	sorterGroup.PUT("/pieces/:id/review", routes.ReviewSorterPiece)
	sorterGroup.GET("/pieces/:id/journey", routes.GetSorterPieceJourney)
	sorterGroup.GET("/runs", routes.ListSorterRuns)
	sorterGroup.GET("/incidents", routes.ListSorterIncidents)
	sorterGroup.GET("/stats", routes.GetSorterStats)
	sorterGroup.GET("/catalog", routes.ListSorterCatalog)
	sorterGroup.GET("/catalog/facets", routes.GetSorterCatalogFacets)
	sorterGroup.GET("/catalog/part", routes.GetSorterCatalogPart)
	sorterGroup.DELETE("/catalog", routes.ClearSorterCatalog)
	sorterGroup.POST("/catalog/fill", routes.FillSorterCatalog)
	sorterGroup.GET("/photos", routes.GetSorterPhotos)
	sorterGroup.DELETE("/photos", routes.ClearSorterPhotos)
	sorterGroup.POST("/incident/resolve", routes.ResolveSorterIncident)
	sorterGroup.GET("/cameras", routes.GetSorterCameras)
	sorterGroup.GET("/cameras/devices", routes.ListSorterCameraDevices)
	sorterGroup.GET("/cameras/modes", routes.ListSorterCameraModes)
	sorterGroup.POST("/cameras/find", routes.FindSorterCameras)
	sorterGroup.GET("/cameras/find", routes.GetSorterCameraFind)
	sorterGroup.GET("/cameras/find/:channel/:which", routes.GetSorterCameraFindImage)
	sorterGroup.GET("/cameras/preview/status", routes.GetSorterCameraPreviewStatus)
	sorterGroup.GET("/cameras/preview/stream", routes.StreamSorterCameraPreview)
	sorterGroup.GET("/cameras/:channel/frame", routes.GetSorterCameraFrame)
	sorterGroup.GET("/cameras/:channel/stream", routes.StreamSorterCamera)
	sorterGroup.GET("/cameras/:channel/observation", routes.GetSorterCameraObservation)
	sorterGroup.POST("/cameras/:channel/background", routes.CaptureSorterBackground)
	sorterGroup.POST("/cameras/:channel/background/round", routes.CaptureSorterRound)
	sorterGroup.POST("/cameras/:channel/measure", routes.MeasureSorterRing)
	sorterGroup.GET("/journeys", routes.ListSorterJourneys)
	sorterGroup.GET("/journeys/:id", routes.GetSorterJourney)
	sorterGroup.GET("/journeys/:id/files/:name", routes.GetSorterJourneyFile)

	registerFrontendHosting(r, cfg.Frontend)
}
